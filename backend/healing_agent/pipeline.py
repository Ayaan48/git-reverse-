"""End-to-end orchestration of a single analyze run.

Runs on a worker thread; every state change is published to the job so the
dashboard reflects progress live rather than at the end.

Stage failures are contained: telemetry, status, and remediation are all
best-effort, because none of them should be able to stop the agent from
repairing code and delivering a branch.
"""

